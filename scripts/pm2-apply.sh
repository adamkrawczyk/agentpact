#!/usr/bin/env bash
# scripts/pm2-apply.sh — apply deploy/ecosystem.config.cjs to the running pm2.
#
# Called by .github/workflows/deploy.yml after build + migrate, with the prod
# env already sourced. Steps:
#   1. Write <app root>/ecosystem.config.cjs as a one-line shim that requires
#      the tracked deploy/ecosystem.config.cjs, so operators who run
#      `pm2 reload ecosystem.config.cjs` by hand get the canonical config.
#   2. `pm2 reload` cannot change an app's exec_mode. Any app whose running
#      mode differs from the canonical one is deleted first so the next step
#      starts it fresh in the right mode. This happens once per mode change
#      (fork -> cluster) and costs that app one restart-length gap; every
#      later reload of a cluster-mode app is zero-downtime.
#   3. `pm2 startOrReload` the ecosystem: starts missing apps, reloads the
#      rest (cluster apps: new worker first, old one drained after it reports
#      ready; fork apps: plain restart).
#   4. `pm2 save`, so a resurrect brings back the same modes.
#
# NEVER print raw `pm2 jlist`: each entry embeds the full process env
# (secrets) and the deploy log is public. Only names and modes are read here.
#
# Usage:
#   bash scripts/pm2-apply.sh                # run from anywhere; acts on repo root
#   bash scripts/pm2-apply.sh --self-test    # fake pm2, touches nothing real

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# Prints "name desired_mode" for every app in the canonical ecosystem.
desired_modes() {
  node -e '
    const apps = require(process.argv[1]).apps;
    for (const a of apps) console.log(a.name + " " + (a.exec_mode === "cluster" ? "cluster_mode" : "fork_mode"));
  ' "$1/deploy/ecosystem.config.cjs"
}

# Prints "name running_mode" for every app pm2 knows. Reads jlist on stdin.
running_modes() {
  node -e '
    let raw = "";
    process.stdin.on("data", (c) => (raw += c));
    process.stdin.on("end", () => {
      const start = raw.indexOf("[");
      const procs = start >= 0 ? JSON.parse(raw.slice(start)) : [];
      for (const p of procs) console.log(p.name + " " + ((p.pm2_env || {}).exec_mode || "unknown"));
    });
  '
}

apply() {
  local root="$1"
  cd "$root"

  cat > ecosystem.config.cjs <<'EOF'
// GENERATED by scripts/pm2-apply.sh on every deploy. Do not edit here:
// edit deploy/ecosystem.config.cjs in the repository.
module.exports = require("./deploy/ecosystem.config.cjs");
EOF

  local desired running name mode current
  desired="$(desired_modes "$root")"
  running="$(pm2 jlist | running_modes)"

  while read -r name mode; do
    [[ -z "$name" ]] && continue
    current="$(awk -v n="$name" '$1 == n { print $2; exit }' <<<"$running")"
    if [[ -n "$current" && "$current" != "$mode" ]]; then
      echo "pm2-apply: $name runs in $current, canonical is $mode; recreating (one-time mode switch)"
      pm2 delete "$name" >/dev/null
    fi
  done <<<"$desired"

  pm2 startOrReload ecosystem.config.cjs --update-env
  pm2 save >/dev/null
  echo "pm2-apply: applied $(wc -l <<<"$desired" | tr -d ' ') app(s) from deploy/ecosystem.config.cjs"
}

self_test() {
  local tmp fails=0
  tmp="$(mktemp -d)"
  trap 'rm -rf "$tmp"' RETURN
  mkdir -p "$tmp/root/deploy" "$tmp/bin"
  cp "$ROOT/deploy/ecosystem.config.cjs" "$tmp/root/deploy/"
  printf 'DATABASE_URL=postgres://u:p@h:6543/d\n' > "$tmp/env"

  # Fake pm2: jlist answers from $FAKE_JLIST, every call is logged.
  cat > "$tmp/bin/pm2" <<'EOF'
#!/usr/bin/env bash
echo "$*" >> "$PM2_CALLS"
if [[ "$1" == "jlist" ]]; then cat "$FAKE_JLIST"; fi
EOF
  chmod +x "$tmp/bin/pm2"

  run_case() {  # $1 = jlist json
    : > "$tmp/calls"
    printf '%s' "$1" > "$tmp/jlist"
    PATH="$tmp/bin:$PATH" PM2_CALLS="$tmp/calls" FAKE_JLIST="$tmp/jlist" \
      AGENTPACT_ENV_FILE="$tmp/env" apply "$tmp/root" >/dev/null
  }
  check() {  # $1 = description, rest = command that must succeed
    local desc="$1"; shift
    if "$@"; then echo "ok   $desc"; else echo "FAIL $desc"; fails=$((fails + 1)); fi
  }
  # The helpers below are called through check "$@", which shellcheck cannot see.
  # shellcheck disable=SC2329
  absent() {  # absent PATTERN: no line of the call log matches
    ! grep -q "$1" "$tmp/calls"
  }
  # shellcheck disable=SC2329
  delete_before_reload() {
    [[ "$(grep -n 'delete ap-api' "$tmp/calls" | cut -d: -f1)" -lt "$(grep -n startOrReload "$tmp/calls" | cut -d: -f1)" ]]
  }
  # shellcheck disable=SC2329
  shim_resolves() {
    local script
    script="$(cd "$tmp/root" && AGENTPACT_ENV_FILE="$tmp/env" node -e 'const a=require(process.cwd()+"/ecosystem.config.cjs").apps; console.log(a.find(x=>x.name==="ap-api").script)')"
    [[ "$script" == "$tmp/root/apps/api/dist/server.js" ]]
  }
  # shellcheck disable=SC2329
  no_secret_in_output() {
    local out
    out="$(PATH="$tmp/bin:$PATH" PM2_CALLS="$tmp/calls" FAKE_JLIST="$tmp/jlist" AGENTPACT_ENV_FILE="$tmp/env" apply "$tmp/root")"
    [[ "$out" != *SECRET* ]]
  }
  j() { printf '{"name":"%s","pm2_env":{"exec_mode":"%s","env":{"SECRET":"x"}}}' "$1" "$2"; }

  # Case 1: today's prod — everything fork. api/web must be recreated, mcp/relayer must not.
  run_case "[$(j ap-api fork_mode),$(j ap-web fork_mode),$(j ap-mcp fork_mode),$(j ap-relayer fork_mode)]"
  check "fork->cluster: deletes ap-api" grep -qx 'delete ap-api' "$tmp/calls"
  check "fork->cluster: deletes ap-web" grep -qx 'delete ap-web' "$tmp/calls"
  check "fork->cluster: leaves mcp/relayer alone" absent 'delete ap-mcp\|delete ap-relayer'
  check "fork->cluster: startOrReload" grep -qx 'startOrReload ecosystem.config.cjs --update-env' "$tmp/calls"
  check "fork->cluster: pm2 save" grep -qx 'save' "$tmp/calls"
  # The delete must come BEFORE startOrReload, or the reload keeps fork mode.
  check "fork->cluster: delete precedes startOrReload" delete_before_reload

  # Case 2: already converged — no deletes, plain reload. This is every deploy after the first.
  run_case "[$(j ap-api cluster_mode),$(j ap-web cluster_mode),$(j ap-mcp fork_mode),$(j ap-relayer fork_mode)]"
  check "converged: no deletes" absent '^delete'
  check "converged: startOrReload" grep -qx 'startOrReload ecosystem.config.cjs --update-env' "$tmp/calls"

  # Case 3: empty pm2 (fresh box) — nothing to delete, startOrReload starts all.
  run_case "[]"
  check "fresh box: no deletes" absent '^delete'

  # Case 4: jlist preceded by a pm2 banner line still parses.
  run_case ">>>> In-memory PM2 is out-of-date
[$(j ap-api fork_mode)]"
  check "banner before jlist: still parsed" grep -qx 'delete ap-api' "$tmp/calls"

  # The shim must resolve to the canonical config with the right app root.
  check "shim resolves canonical config at the app root" shim_resolves

  # Output must never carry env values from jlist.
  check "never echoes jlist env" no_secret_in_output

  if [[ "$fails" -gt 0 ]]; then echo "pm2-apply self-test: $fails failure(s)"; return 1; fi
  echo "pm2-apply self-test: all checks passed"
}

if [[ "${1:-}" == "--self-test" ]]; then
  self_test
  exit $?
fi

apply "$ROOT"
